// Initial 40 seats for standard 40-seater luxury coach - all available at start
export const generateInitialSeats = (): Seat[] => {
  const seats: Seat[] = [];
  const rows = ['A', 'B', 'C', 'D', 'E', 'F', 'G', 'H', 'I', 'J'];
  let seatNumber = 1;

  for (let r = 0; r < rows.length; r++) {
    for (let c = 1; c <= 4; c++) {
      const label = `${rows[r]}${c}`;
      seats.push({
        id: seatNumber,
        label,
        number: seatNumber,
        status: 'available',
        bookedBy: undefined
      });

      seatNumber++;
    }
  }

  return seats;
};

